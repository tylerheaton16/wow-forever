3357 3818 3821 3358 3819 4625 8836 8831 2776 3858 4338 4234 11137 11135 11177 11178 \
4339 4236 3860 3859 3577 4387 10559 10561 10560 \
13464 8838 8839 8845 8846 13463 13465 13466 13467 7911 10620 11370 \
14047 4304 8170 11176 11175 14343 14344 14048 8172 6037 12359 11371 \
15994 18631 16000"

tmp=$(mktemp)
curl -fsS "$URL" -o "$tmp"

{
  echo "// Generated by refresh-prices.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "// Source: $URL (prices in copper)"
  echo "window.PRICES_META = { fetched: \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\", market: \"US / Normal ruleset / Horde\" };"
  echo "window.PRICES = {"
  # Columns: itemId,name,marketValue,minBuyout,recent,historical,updatedAt
  # Name may contain commas, so take numeric fields from the row's end.
  awk -F, -v ids="$IDS" '
    BEGIN { n = split(ids, a, /[ \t]+/); for (i = 1; i <= n; i++) want[a[i]] = 1 }
    NR > 1 && ($1 in want) {
      name = $2
      for (i = 3; i <= NF - 5; i++) name = name "," $i
      gsub(/"/, "\\\"", name)
      printf "  \"%s\": {name:\"%s\", mv:%d, min:%d, updated:\"%s\"},\n", $1, name, $(NF-4), $(NF-3), $NF
    }' "$tmp"
  echo "};"
} > prices.js

rm -f "$tmp"
count=$(grep -c '^  "' prices.js)
echo "Wrote prices.js with $count items."
