#!/usr/bin/env bash
# Regenerates prices.js from TSM's public WoW Forever data (US / Normal / Horde).
# Data updates every few hours; TSM asks for attribution when using this data.
set -euo pipefail
cd "$(dirname "$0")"

URL="https://public-data.tradeskillmaster.com/forever/us/realm/normal-horde/items.csv"

# Every itemId the page needs: 30 crates + all fill items.
IDS="248682 248683 248684 248685 248686 248687 248688 248689 248690 248691 \
248692 248693 248694 248695 248696 248697 248698 248699 248702 248703 \
248704 248705 248706 248707 248708 248709 248710 248711 248712 248713 \
